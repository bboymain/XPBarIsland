local function spellKey(name, rank)
    return name .. "\t" .. (rank or "")
end

local function validCost(cost)
    return type(cost) == "number" and cost >= 0 and cost < math.huge and cost == math.floor(cost)
end

function ns.TrainingCost(spell)
    local class = select(2, UnitClass("player"))
    local cache = XPBarIslandDB and XPBarIslandDB.trainerCosts
    cache = type(cache) == "table" and cache[class]
    if type(cache) ~= "table" then cache = nil end
    local cost = cache and cache[spell.id]
    if not validCost(cost) then cost = cache and cache[spellKey(spell.name, spell.rank)] end
    if validCost(cost) then return cost end
    local entry = ns.trainingCosts[class] and ns.trainingCosts[class][spell.id]
    if entry and validCost(entry.cost) then return entry.cost, "bundled" end
end

function ns.TrainingMoney(cost)
    if cost == nil then return "?" end
    if GetCoinTextureString then
        local ok, coins = pcall(GetCoinTextureString, cost, 10)
        if ok and type(coins) == "string" and coins ~= "" then return coins end
    end
    -- Some clients omit the helper; use Blizzard's coin textures directly.
    local coins = {}
    local gold, silver, copper = math.floor(cost / 10000), math.floor(cost / 100) % 100, cost % 100
    if gold > 0 then coins[#coins + 1] = gold .. "|TInterface\\MoneyFrame\\UI-GoldIcon:10:10:0:0|t" end
    if silver > 0 then coins[#coins + 1] = silver .. "|TInterface\\MoneyFrame\\UI-SilverIcon:10:10:0:0|t" end
    if copper > 0 or #coins == 0 then coins[#coins + 1] = copper .. "|TInterface\\MoneyFrame\\UI-CopperIcon:10:10:0:0|t" end
    return table.concat(coins, " ")
end

function ns.TrainingTotal(spells)
    local total, unknown = 0, false
    for _, spell in ipairs(spells) do
        local cost = ns.TrainingCost(spell)
        if cost == nil then unknown = true else total = total + cost end
    end
    return (unknown and "~" or "") .. ns.TrainingMoney(total) .. (unknown and "+" or ""), unknown
end

local function updateTrainerCosts()
    if not (GetTrainerServiceCost and GetNumTrainerServices and GetTrainerServiceInfo
        and GetTrainerServiceLevelReq and XPBarIslandDB) then return end
    if IsTradeskillTrainer and IsTradeskillTrainer() then return end
    local class = select(2, UnitClass("player"))
    local levels = ns.classSpells[class]
    if not levels then return end
    -- Match name, rank AND level to our class list before accepting a price;
    -- profession, weapon, riding and pet trainers must not seed class prices.
    local matches = {}
    for level, ids in pairs(levels) do
        for _, id in ipairs(ids) do
            local name, rank
            if GetSpellInfo then name, rank = GetSpellInfo(id)
            elseif C_Spell and C_Spell.GetSpellInfo then
                local info = C_Spell.GetSpellInfo(id)
                if info then name, rank = info.name, info.subName end
            end
            if name then matches[spellKey(name, rank) .. "\t" .. level] = id end
        end
    end
    local services, classTrainer = {}, false
    for i = 1, GetNumTrainerServices() do
        local name, rank, category = GetTrainerServiceInfo(i)
        if name and category ~= "header" then
            local level = GetTrainerServiceLevelReq(i)
            local id = level and matches[spellKey(name, rank) .. "\t" .. level]
            if id then classTrainer = true end
            local cost = GetTrainerServiceCost(i)
            -- Learned services can report zero instead of their training price.
            if category ~= "used" and validCost(cost) then
                services[#services + 1] = { key = spellKey(name, rank), id = id, cost = cost }
            end
        end
    end
    if not classTrainer then return end
    local caches = XPBarIslandDB.trainerCosts
    if type(caches) ~= "table" then caches = {}; XPBarIslandDB.trainerCosts = caches end
    if type(caches[class]) ~= "table" then caches[class] = {} end
    for _, service in ipairs(services) do
        caches[class][service.key] = service.cost
        if service.id then caches[class][service.id] = service.cost end
    end
    ns.MarkDirty()
end

ns.On("TRAINER_SHOW", updateTrainerCosts)
ns.On("TRAINER_UPDATE", updateTrainerCosts)
