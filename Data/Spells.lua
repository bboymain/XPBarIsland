-- Runtime lookup: the spells a class learns at `level`, ready to display.
-- Prefers the client's own list when it exists, then the bundled table.
-- Spells already known (or that this client cannot resolve) are dropped.
-- Every client call is guarded so a missing API can never break the XP data.
local cache = {}

-- Spell name/icon on clients with or without the deprecated global.
local function spellInfo(id)
    local g = _G.GetSpellInfo
    if type(g) == "function" then
        local ok, name, _, icon = pcall(g, id)
        if ok and name then return name, icon end
    end
    local cs = _G.C_Spell
    if cs and type(cs.GetSpellInfo) == "function" then
        local ok, info = pcall(cs.GetSpellInfo, id)
        if ok and type(info) == "table" then return info.name, info.iconID or info.originalIconID end
    end
    return nil
end

local function isKnown(id)
    local f = _G.IsSpellKnown
    if type(f) == "function" then
        local ok, k = pcall(f, id)
        if ok then return k end
    end
    return false
end

function ns.SpellsForLevel(level)
    if not level then return {} end
    if cache[level] then return cache[level] end
    local ids = {}
    local get = _G.C_SpellBook and _G.C_SpellBook.GetCurrentLevelSpells
    if type(get) == "function" then
        local ok, res = pcall(get, level)
        if ok and type(res) == "table" then
            for _, id in ipairs(res) do ids[#ids + 1] = id end
        end
    end
    if #ids == 0 then
        local token = select(2, UnitClass("player"))
        local t = ns.classSpells and token and ns.classSpells[token]
        local list = t and t[level]
        if list then for i = 1, #list do ids[#ids + 1] = list[i] end end
    end
    local out = {}
    for i = 1, #ids do
        local id = ids[i]
        local name, icon = spellInfo(id)
        if name and not isKnown(id) then
            out[#out + 1] = { id = id, name = name, icon = icon }
        end
    end
    cache[level] = out
    return out
end

-- The next level above `level` that teaches new spells for the player's class.
function ns.NextSpellLevel(level)
    local token = select(2, UnitClass("player"))
    local t = ns.classSpells and token and ns.classSpells[token]
    if not t then return nil end
    local best
    for lvl, list in pairs(t) do
        if type(lvl) == "number" and lvl > (level or 0) and #list > 0 and (not best or lvl < best) then
            best = lvl
        end
    end
    return best
end

ns.On("SPELLS_CHANGED", function() cache = {} end)
ns.On("PLAYER_LEVEL_UP", function() cache = {} end)